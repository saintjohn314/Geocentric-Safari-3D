// Writes public/sw.js: an offline-first service worker that precaches every file in public/.
// The cache name is a content hash, so any change to any file ships a fresh cache.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, sep } from 'node:path';

const root = join(new URL('.', import.meta.url).pathname, '..', 'public');
const skip = new Set(['sw.js', '404.html', 'robots.txt', 'sitemap.xml', 'README.txt', 'LICENSE']);
const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (!skip.has(name) && !name.startsWith('og-')) files.push(relative(root, p).split(sep).join('/'));
  }
};
walk(root);
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(root, f)));
const version = hash.digest('hex').slice(0, 12);
const list = ['./', ...files.filter((f) => f !== 'index.html')];

writeFileSync(join(root, 'sw.js'), `// Generated by scripts/precache.mjs - do not edit by hand.
const CACHE = 'gs3d-${version}';
const PRECACHE = ${JSON.stringify(list, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('gs3d-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    // Network first for the page itself so new releases show up promptly; cached copy when offline.
    event.respondWith(fetch(request).catch(() => caches.match('./')));
    return;
  }
  event.respondWith(
    caches.match(request).then((hit) => hit || fetch(request).then((res) => {
      if (res.ok) {
        const copy = res.clone();
        caches.open(CACHE).then((cache) => cache.put(request, copy));
      }
      return res;
    })),
  );
});
`);
console.log(`sw.js: ${list.length} files, cache ${version}`);
